export interface TitleDesignSpec {
  angles: string
  systemPrompt: string
}

// ===== 通用标题（小说/诗歌/散文等非爆款内容）=====
const GENERIC_ANGLES = '1.悬念疑问式\n2.反常识式\n3.共鸣痛点式\n4.对比冲击式\n5.两难选择式\n6.温情治愈式'
const GENERIC_SYSTEM_PROMPT = '你是专业的标题设计师，根据文章内容生成贴合内文的标题，只返回6行标题，不要加任何解释。'

// ===== 知乎/自媒体爆款标题（6 套公式）=====
export const ZHIHU_ANGLES = `1.身份反差+极端事件（普通身份遭遇不该发生的事）
2.时间锚点+戏剧反转（X天后/后，完全相反的结果）
3.痛点场景+反问（"你是不是也…？"）
4.数字+痛点+承诺（数字+扎心场景+给解法）
5.反常识断言（大家都信的，其实是错的）
6.两难选择（A还是B，没有完美解）`

export const ZHIHU_SYSTEM_PROMPT = `你是知乎爆款标题设计师。生成的标题必须满足以下 4 个要素（缺一不可）：
1. 身份/人群锚点：32岁、月薪5千、985硕士、宝妈、程序员——让人对号入座
2. 具体数字或时间：6个月、47天、200份简历、35岁门槛——数字制造真实感和冲击
3. 冲突/反差/反常识：高不成低不就、越省越穷、明明有ETC却排队——大脑对矛盾自动停手
4. 悬念或未完成缺口：为什么…、到底谁在定、是不是该认命了——蔡格尼克效应，不点开难受

知乎标题的本质是「问题 + 情绪 + 身份锚点」。别写"如何学习理财"这种菜市场吆喝，要写"32岁定投6个月只赚杯奶茶钱，是不是我方法错了？"

细节规范：
- 30 字内覆盖核心搜索词（如"32岁失业""基金回撤"），方便 SEO 抓取
- 用中文逗号分段，可两段或三段："场景，冲突，问句"结构最稳
- 慎用"震惊/惊呆/99%人都错了"——知乎审核和老用户反感，易限流
- 问题标题要比回答标题更像"真人提问"，回答标题可稍带观点，但别做成公众号体
- 加引号强调关键词："高不成低不就""透明人"能提高辨识度

绝对别碰的坑：
- 纯陈述无问号（没缺口，不点）
- 抽象概括（像论文目录）
- 标题党、内容和正文不符（跳出率一高账号权重直接掉）
- 同时塞 5 个热点（算法不知道推给谁，人群分散必凉）
- 用"干货/实用/指南"安全词替代痛点（没人搜"实用指南"，只搜"被拒17次怎么办"）`

/** 根据文章类型返回标题设计规范：知乎/自媒体用爆款公式，其它类型用通用角度 */
export function getTitleDesignSpec(articleTypeId?: string): TitleDesignSpec {
  if (articleTypeId === 'zhihu' || articleTypeId === 'social') {
    return { angles: ZHIHU_ANGLES, systemPrompt: ZHIHU_SYSTEM_PROMPT }
  }
  return { angles: GENERIC_ANGLES, systemPrompt: GENERIC_SYSTEM_PROMPT }
}
